fns = list(rows[0].keys())
for c in ["改动类型", "依据/口径"]:
    if c not in fns:
        fns.append(c)

stat = {}
for r in rows:
    n = r["合同项名"].strip()
    if n in E:
        t, note = "保留待定(残片)", "建议合同录入端建词表合并"
    elif n in A:
        t, note = "直接改映射值", A[n]
