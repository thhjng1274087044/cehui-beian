def parse_checked(text):
    """解析「名称【标记】」，返回已勾选项名(去重保序) + 全部项名"""
    checked, allitems = [], []
    for m in re.finditer(r'([\u4e00-\u9fa5]{2,12})【([^】]{0,3})】', text or ""):
        name, flag = m.group(1), m.group(2).strip()
        allitems.append(name)
        if flag and any(c in flag for c in CHECK_MARKS) and name not in checked:
            checked.append(name)
    return checked, allitems


def parse_content(text):
    """L2：解析「一、项目内容：XXX」"""
    m = re.search(r'项目内容[：:]\s*([^\n]{2,80})', text or "")
    if not m:
        return []
    seg = m.group(1)
    parts = re.split(r'[、,，;；及和]', seg)
    return [p.strip(" 。.）)") for p in parts if len(p.strip()) >= 2]


def norm_items(names):
    """项名 -> 平台类型列表（去重保序）+ 未映射项"""
    plat, unmapped = [], []
    for n in names:
        hit = ITEM2PLATFORM.get(n)
        if hit is None:
            unmapped.append(n); continue
        t = f"{hit[0]}/{hit[1]}" if hit[1] else hit[0]
        if t not in plat:
            plat.append(t)
    return plat, unmapped


